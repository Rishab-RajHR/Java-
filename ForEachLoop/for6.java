// package ForEachLoop;

public class for6 {
    public static void main(String[] args) {
        int [] marks = {98, 45, 79, 99, 80};

        // for Each loop in displaying data
        System.out.println("Printing using for-each loop");
        for(int element: marks) {
            System.out.println(element);
        }
    }
}
